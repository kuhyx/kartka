"""Render the open signatures as ``TODO-fixme.md``: a prompt, then the bugs.

The file is a task file (md-file-conventions), so it starts with the
``REMOVE ME AFTER FINISH`` marker and is deleted as soon as nothing is
open. It is gitignored and regenerated on every ingest: never edit it.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from kartka_errors.state import open_signatures

if TYPE_CHECKING:
    from pathlib import Path

    from kartka_errors.state import SigRecord, State

MARKER = "<!-- REMOVE ME AFTER FINISH -->"
#: Signatures written out; the rest are counted at the end.
MAX_SECTIONS = 30
#: Stack frames shown per signature.
MAX_FRAMES = 8

PROMPT = """\
Fix each error below in kartka (~/src/kartka). They were reported
automatically by kartka on kuhy's devices (redacted; URLs, tokens and
emails are masked). Read CLAUDE.md, docs/DOCS-spec.md and
docs/DOCS-contracts-runtime.md first. Then, one signature at a time:

1. Find the cause from the message, the top frame, the route and the kind
   (`ui.snackbar` = an error snackbar, `uncaught.*` = an escaped exception,
   `reader.open` / `details.load` / `browse.page` = a Retry screen).
2. Reproduce it: write a failing test first, and run it red.
3. Fix it, run the same test green, then the tests of the files you
   changed (never the whole suite in one call; 60 s cap per command).
4. Commit (`<area>: <imperative summary>`), then mark it fixed with
   `tools/errors/run.sh resolve <signature>`. It reopens by itself if the
   error is reported again after the fix.

If an error is not a bug in kartka (a source that is down, a server
setting), say so instead of patching around it, and resolve it only once
kuhy agrees. Do not edit this file: it is regenerated every 15 minutes."""


def _section(rec: SigRecord) -> list[str]:
    sample = rec["sample"]
    head = sample["error"].splitlines()[0][:100] if sample["error"] else "?"
    lines = [
        f"## {head}" if head.startswith(rec["type"]) else f"## {rec['type']}: {head}",
        "",
        f"- signature: `{rec['id']}`" + (" (reopened)" if rec["reopened"] else ""),
        f"- count: {rec['count']}, first seen {rec['first']}, last seen {rec['last']}",
        f"- kinds: {', '.join(rec['kinds'])}",
        f"- devices: {', '.join(rec['devices'])}",
        f"- top frame: `{rec['where']}`",
    ]
    if rec["routes"]:
        lines.append(f"- routes: {', '.join(f'`{r}`' for r in rec['routes'])}")
    if rec["sources"]:
        lines.append(f"- sources: {', '.join(rec['sources'])}")
    lines.extend(
        f"- last {field}: `{value}`"
        for field in ("mangaUrl", "chapterUrl")
        if (value := sample.get(field))
    )
    lines += ["", "```text", sample["error"], "```"]
    if stack := sample.get("stack"):
        lines += ["", "Stack (excerpt):", "", "```text", *stack[:MAX_FRAMES], "```"]
    return [*lines, ""]


def render(state: State, now: str) -> str | None:
    """The TODO file for ``state``; None when no signature is open."""
    records = open_signatures(state)
    if not records:
        return None
    lines = [
        MARKER,
        "# TODO: fix the errors kartka reported",
        "",
        (
            f"Generated {now} by `tools/errors` from `/kartka/errors`:"
            f" {len(records)} open signature(s)."
        ),
        "",
        "## Prompt",
        "",
        PROMPT,
        "",
    ]
    for rec in records[:MAX_SECTIONS]:
        lines += _section(rec)
    if (more := len(records) - MAX_SECTIONS) > 0:
        lines.append(f"... and {more} more (fix these first, they rerender).")
    return "\n".join(lines).rstrip() + "\n"


def write_todo(out: Path, text: str | None) -> str:
    """Write ``text`` to ``out``, or delete ``out`` when it is None."""
    if text is not None:
        out.write_text(text)
        return "wrote"
    if out.exists():
        out.unlink()
        return "removed"
    return "nothing open"
