// Bundles node-html-parser (MIT) and its dependencies into one ES2017 IIFE and
// writes it as a Dart string constant, plus a combined licence file.
// Run: `pnpm install && pnpm build` in this directory.
import { build } from 'esbuild';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const result = await build({
  entryPoints: ['entry.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2017',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  write: false,
  legalComments: 'none',
});
const code = result.outputFiles[0].text;
const escaped = code
  .replaceAll('\\', '\\\\')
  .replaceAll("'", "\\'")
  .replaceAll('$', '\\$')
  .replaceAll('\n', '\\n');
writeFileSync(
  '../html_parser_bundle.g.dart',
  `// GENERATED by js/build.mjs from node-html-parser; do not edit.
// Licences: js/THIRD_PARTY_LICENSES.txt.
// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes

/// node-html-parser and its dependencies as one IIFE (exposes
/// \`globalThis.__kartka_html_parse\`).
const String kHtmlParserBundle = '${escaped}';
`,
);

// Licence texts of every package that ended up in the bundle.
const store = 'node_modules/.pnpm';
const wanted = ['node-html-parser', 'css-select', 'css-what', 'boolbase',
  'domhandler', 'domelementtype', 'domutils', 'dom-serializer', 'entities',
  'nth-check'];
let out = 'Third-party code bundled into html_parser_bundle.g.dart.\n\n';
for (const dir of readdirSync(store).sort()) {
  const name = dir.replace(/@[^@]*$/, '');
  if (!wanted.includes(name)) continue;
  const pkgDir = join(store, dir, 'node_modules', name);
  const file = readdirSync(pkgDir).find((f) => /^licen[cs]e/i.test(f));
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  out += `==== ${pkg.name}@${pkg.version} (${pkg.license}) ====\n`;
  out += file ? readFileSync(join(pkgDir, file), 'utf8') : '(no licence file)';
  out += '\n\n';
}
writeFileSync('THIRD_PARTY_LICENSES.txt', out);
writeFileSync(
  '../third_party_licenses.g.dart',
  `// GENERATED by js/build.mjs; do not edit.
// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes

/// Licences of the code inside the bundled HTML parser.
const String kHtmlParserLicenses = '${out
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('$', '\\$')
    .replaceAll('\n', '\\n')}';
`,
);
console.log(`bundle ${code.length} bytes`);
